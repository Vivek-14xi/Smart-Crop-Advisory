function getLocalizedSchemeName(scheme, language) {
  const lang = String(language || 'en').toLowerCase().split('-')[0]
  return schemeNameTranslations[lang]?.[scheme.id] || scheme.name
}

function getSchemeCardTranslation(scheme, language, field) {
  const lang = String(language || 'en').toLowerCase().split('-')[0]
  const fieldIndex = {
    category: 0,
    description: 1,
    benefits: 2,
    eligibility: 3
  }[field]

  const translation = schemeCardTranslations[lang]?.[scheme.id]
  if (translation && fieldIndex !== undefined && translation[fieldIndex]) {
    return translation[fieldIndex]
  }

  return scheme[field] || ''
}

